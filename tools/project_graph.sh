#!/bin/sh
# Generate the project graph (docs/PROJECT_GRAPH.md) on stdout.
#
# WHY. An agent answering "what depends on scan.sd7" or "who includes progs.s7i" pays a read per
# module. The graph is the whole shape in one read, so it is generated from the tree rather than
# hand-kept: a hand-kept map is a second source of truth that drifts.
#
# HOW. Includes come from one anchored `grep -oE`: the pattern must start at the line head (after
# optional indentation and an optional `$`), which is what keeps COMMENT prose out of the graph --
# src/blocks.sd7:217 writes the phrase include "x" inside a sentence about both include forms, and
# with the anchor deleted that row gains the false edge `x` (measured by mutation;
# tests/graph_test.sh requires the row to be `scan.sd7` and nothing else). Rows are
# `name lines includes`, src/ modules first then src/features/ (feature rows keep the `features/`
# prefix), each alphabetically under LC_ALL=C, so the artifact is byte-stable across runs and `cmp`
# against the committed copy is meaningful.
#
# The methods slice reads two files and runs no interpreter: tools/lsp_methods.tsv (the frozen LSP
# 3.18 clientToServer|both inventory, regenerated by hand with tools/lsp_methods_regen.sh) and
# src/lsp_server.sd7 (the dispatcher's `msg.method = "..."` chain and the capabilitiesJson tree).
#
# shortcut: no reverse edges and no test-suite section -- `## modules`, `## methods` and
#           `## reconciliation` are the whole artifact until Task 4 appends the suite map.
# shortcut: the capability path set is keyed on indentation (see cap_paths), because Seed7 has no
#           machine-readable description of ServerCapabilities.
# shortcut: `for x in $(find ...)` word-splits, so a module path with a space would become two
#           rows. Upgrade to a `while IFS= read -r` loop (tools/agents_gate.sh) the day one exists.
# shortcut: the guard checks src/ only, so a tree without src/features still exits 0 and writes a
#           16-row artifact (measured: 0 feature rows, 63 stderr bytes). tests/graph_test.sh reddens
#           that on the stderr check and on the feature-row count.
#
# Usage:  sh tools/project_graph.sh > docs/PROJECT_GRAPH.md    # also `make graph`;
#         wired into `make test` as TESTS_SH := graph via tests/graph_test.sh, and it stays fast
#         because it only reads the repo's own src/ and tools/lsp_methods.tsv.

set -eu
LC_ALL=C
export LC_ALL

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
[ -d "$ROOT/src" ] || { printf 'project_graph: no src/ under %s\n' "$ROOT" >&2; exit 1; }
SERVER="$ROOT/src/lsp_server.sd7"
METHODS="$ROOT/tools/lsp_methods.tsv"
# A missing inventory would otherwise write an artifact with no method rows at all, and `make graph`
# would bless it: tests/graph_test.sh's "every tsv method appears exactly once" reads the same tsv, so
# it cannot see the file it is missing.
[ -r "$METHODS" ] || { printf 'project_graph: no tools/lsp_methods.tsv -- run: sh tools/lsp_methods_regen.sh > tools/lsp_methods.tsv\n' >&2; exit 1; }
# SERVER is read twice -- the dispatcher's method list and the capabilitiesJson tree -- and both reads
# sit in a command substitution whose status `tr' masks, so an unreadable SERVER would give an empty
# `answered', an empty `paths', a full 75-row all-`-' artifact and a reconciliation that says `clean`.
[ -r "$SERVER" ] || { printf 'project_graph: no src/lsp_server.sd7\n' >&2; exit 1; }

INCLUDE_RE='^[[:space:]]*(\$[[:space:]]*)?include[[:space:]]+"[^"]+"'
METHOD_RE='msg\.method = "[^"]+"'

row() { # $1 = name to print, $2 = file to read
  lines=$(wc -l < "$2")
  includes=''
  stdlib=''
  # -o, not just -E: a line holding two includes is two edges; sort -u folds one spelling once.
  for inc in $(grep -oE "$INCLUDE_RE" "$2" | sed -E 's/.*include[[:space:]]+"([^"]+)".*/\1/' | sort -u); do
    case $inc in
      seed7_05.s7i) ;;
      *.s7i) stdlib="$stdlib $inc" ;;
      *) includes="$includes $inc" ;;
    esac
  done
  rest="$includes"
  if [ -n "$stdlib" ]; then
    rest="$rest +stdlib:$stdlib"
  fi
  rest="${rest# }"
  # Two fields when there is nothing to list, so a row never ends in the format's spaces -- and no
  # trim pipeline is needed, which would have turned a fatal in generate() (an unreadable module,
  # say) into exit 0 and a truncated artifact: POSIX sh has no pipefail.
  if [ -n "$rest" ]; then
    printf '%-28s %4d  %s\n' "$1" "$lines" "$rest"
  else
    printf '%-28s %4d\n' "$1" "$lines"
  fi
}

# The dotted capability paths capabilitiesJson writes, one per line. Depth is indentation: a nested
# field in src/lsp_server.sd7 sits one 2-space step deeper than its parent, so a stack keyed on
# (column - the column of the block's first field) / 2 + 1 rebuilds `textDocumentSync.openClose' with
# no JSON parser. The block is read between `capabilitiesJson is func' and the next `^const ' line,
# because initializeResultJson's `field(w, "capabilities")' is a request-result member, not a
# capability, and would otherwise join the set.
# shortcut: indentation-keyed, and it assumes one field per line with no level skipped (a field
#           three levels deep with nothing at level 2 would attach to the wrong parent). Upgrade to
#           parsing the JSON for real if capabilitiesJson is ever reformatted.
cap_paths() {
  base=-1
  stack=''
  sed -n '/^const func string: capabilitiesJson is func$/,/^const /p' "$SERVER" |
  while IFS= read -r line; do
    case $line in *'field(w, "'*) ;; *) continue ;; esac
    indent=${line%%[![:space:]]*}
    if [ "$base" -lt 0 ]; then
      base=${#indent}
    fi
    level=$(((${#indent} - base) / 2 + 1))
    name=${line#*'"'}
    name=${name%%'"'*}
    parents=''
    dotted=''
    depth=0
    for part in $stack; do
      depth=$((depth + 1))
      if [ "$depth" -ge "$level" ]; then
        break
      fi
      parents="$parents $part"
      dotted="$dotted$part."
    done
    stack="$parents $name"
    printf '%s\n' "$dotted$name"
  done
}

# One pass makes the rows AND the reconciliation gaps, because a gap is exactly a row whose two flags
# disagree -- two passes would be two judgements that can drift apart.
# `A': the dispatcher's if-chain names the method. `C': the method's spec capability path is one the
# server writes. The comparison is the WHOLE dotted path, never its first segment: matching
# `completionProvider.resolveProvider' against the advertised `completionProvider' reports five gaps
# that do not exist (measured), which is invariant 5 invented out of thin air. A method with no
# spec capability (`-', like the lifecycle traffic) is not a gap in either direction: there is no
# capability to compare the answer with.
method_inventory() {
  tab=$(printf '\t')
  answered=$(grep -oE "$METHOD_RE" "$SERVER" | sed -E 's/.*"([^"]+)".*/\1/' | sort -u | tr '\n' ' ')
  paths=$(cap_paths | tr '\n' ' ')
  matched=''
  gaps_advertised=''
  gaps_answered=''
  printf '\n## methods (LSP 3.18 clientToServer|both: A = answered, C = capability advertised)\n'
  printf '\n'
  # `kind' (request | notification) is read only to reach the third column: the row format is fixed
  # by tests/graph_test.sh's anchors, which start at the two flags and name no kind.
  while IFS=$tab read -r method kind capability; do
    answered_flag='-'
    case " $answered " in *" $method "*) answered_flag='A'; matched="$matched $method" ;; esac
    advertised_flag='-'
    if [ "$capability" != '-' ]; then
      case " $paths " in *" $capability "*) advertised_flag='C' ;; esac
    fi
    printf '%s %s %-38s %s\n' "$answered_flag" "$advertised_flag" "$method" "$capability"
    # A row whose flags agree answers and advertises the same thing, and a row with no spec
    # capability has nothing to compare: only the two disagreements are gaps.
    if [ "$capability" != '-' ]; then
      if [ "$advertised_flag" = 'C' ] && [ "$answered_flag" = '-' ]; then
        gaps_advertised="$gaps_advertised  advertised without an answer: $method ($capability)
"
      elif [ "$advertised_flag" = '-' ] && [ "$answered_flag" = 'A' ]; then
        gaps_answered="$gaps_answered  answered without capability: $method ($capability)
"
      fi
    fi
  done < "$METHODS"
  # An answered method the frozen inventory does not list gets its own row, flagged A with no
  # capability: without it a method outside the 75 would score no row, no gap and no red, and the
  # count check titled "answered rows equal the dispatcher's method list" would stay green while
  # counting something else.
  for name in $answered; do
    case " $matched " in *" $name "*) continue ;; esac
    printf '%s %s %-38s %s\n' A - "$name" -
  done
  printf '\n## reconciliation (capability advertised with no answer, answer with no capability)\n'
  printf '\n'
  if [ -z "$gaps_advertised$gaps_answered" ]; then
    printf '  clean\n'
  else
    printf '%s' "$gaps_advertised$gaps_answered"
  fi
}

generate() {
  printf '<!-- GENERATED by tools/project_graph.sh -- do not edit; run: make graph -->\n'
  printf '# seed7-lsp-server project graph\n'
  printf '\n'
  printf '## modules (own name -> the src modules it includes)\n'
  printf '\n'
  for file in $(find "$ROOT/src" -maxdepth 1 -name '*.sd7' | sort); do
    row "${file#"$ROOT"/src/}" "$file"
  done
  for file in $(find "$ROOT/src/features" -maxdepth 1 -name '*.sd7' | sort); do
    row "features/${file##*/}" "$file"
  done
  method_inventory
}

generate
